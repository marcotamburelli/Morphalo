import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Optional

from morphalo.cache.models import dtype_key, evict_qwen_image21_pipe, get_qwen_image21_pipe
from morphalo.dag import AttachmentSink, NodeRef
from morphalo.nodes.common.config_resolve import SpecInput, resolve_dtype, resolve_spec
from morphalo.core.cuda_mem import cleanup_torch_cuda, synchronize_torch_cuda
from morphalo.nodes.common.cuda_stat import cuda_mem_stats, cuda_prerun, cuda_sync
from morphalo.nodes.common.device import is_cuda_device
from morphalo.nodes.common.io import save_image
from morphalo.nodes.foundation.qwen_utils import (
    qwen_cpu_generator,
    resolve_qwen_image_edit_params,
    resolve_qwen_seed,
)
from morphalo.nodes.foundation.wiring import ImageSequenceMixin
from morphalo.nodes.image_output import ImageOutputMixin
from morphalo.nodes.io import finalize_image_output
from morphalo.nodes.wiring.mixins import PromptMixin
from morphalo.nodes.wiring.prompt import PromptBundle


DEFAULT_QWEN_IMAGE21_MODEL_ID = 'Qwen/Qwen-Image-2.1'
QWEN_IMAGE21_TURBO_MODEL_ID = 'Qwen/Qwen-Image-2.1-Turbo'


@dataclass
class QwenImage21(ImageOutputMixin, ImageSequenceMixin, PromptMixin, NodeRef):
    """
    Qwen-Image-2.1 unified text-to-image and image-editing node.

    This node runs the Diffusers ``QwenImage21Pipeline``. With no image inputs,
    it generates an image from text. With one or more image inputs, it performs
    instruction-driven editing using an ordered sequence of up to ten reference
    images. Alpha channels are preserved in reference images and the output PNG.

    The node defaults to ``'Qwen/Qwen-Image-2.1'``. The Turbo checkpoint can be
    selected through ``model.id``. Both model weights are subject to the Qwen
    Research License for non-commercial research or evaluation; commercial use
    requires a separate license. See the `model card license section
    <https://huggingface.co/Qwen/Qwen-Image-2.1#license>`_ and the linked
    `Qwen Research License Agreement
    <https://huggingface.co/Qwen/Qwen-Image-2.1/blob/main/LICENSE>`_.

    Parameters
    ----------
    name : str, optional
        Unique node identifier within the DAG. If not provided, an identifier is
        automatically generated by the enclosing DAG.
    spec : SpecInput, optional
        Node configuration specification. Accepts a dictionary, a HOCON file
        path, or a sequence of specifications merged from left to right by
        :func:`resolve_spec`.

        ``model`` keys:

        - ``id`` : str, optional
          Hugging Face model identifier or local Diffusers model directory.
          Defaults to ``'Qwen/Qwen-Image-2.1'``. Use
          ``'Qwen/Qwen-Image-2.1-Turbo'`` for the official Turbo checkpoint.
        - ``dtype`` : str, optional
          Torch dtype used to load model weights. Defaults to ``'bf16'``.
        - ``device`` : str, optional
          Runtime device for pipeline execution. Defaults to ``'cuda'``.
          CUDA device indexes such as ``'cuda:0'`` are supported.
        - ``cpu_offload`` : bool, optional
          If true and ``device`` is CUDA, enable Diffusers model CPU offload,
          moving whole components to the GPU as needed. Otherwise, move the
          full pipeline to ``device``. Defaults to ``True``.
        - ``vae_tiling`` : bool, optional
          Enable tiled VAE encoding and decoding to reduce peak activation
          memory. Defaults to ``False``. Tiling can change fine details and
          alpha values near tile boundaries.

        ``params`` keys:

        - ``steps`` : int, optional
          Requested number of inference steps. Defaults to ``40``, or ``8``
          when ``model.id`` is ``'Qwen/Qwen-Image-2.1-Turbo'``. A sampling
          schedule configured in the checkpoint takes precedence over this
          count; Diffusers loads Turbo's recommended schedule automatically.
        - ``true_cfg_scale`` : float, optional
          True classifier-free guidance scale. When omitted, the pipeline
          default of ``1.0`` is used. Guidance above 1 requires an explicit
          non-empty negative prompt. ``guidance_scale`` is not supported.
        - ``width`` : int, optional
          Explicit output width. Takes precedence over the width derived from
          ``output_resolution``. The pipeline rounds down to a multiple of 32.
        - ``height`` : int, optional
          Explicit output height. Takes precedence over the height derived from
          ``output_resolution``. The pipeline rounds down to a multiple of 32.
        - ``output_resolution`` : int, optional
          Resolution scale used to derive missing output dimensions and resize
          every reference image. The pipeline default is ``1024``. Without
          references, omitted dimensions default to this value. With references,
          the output targets approximately ``output_resolution ** 2`` pixels,
          preserving the aspect ratio of the last reference image. This is not
          a maximum side length. Reference resizing still uses this setting
          when explicit ``width`` and ``height`` are provided.
        - ``use_kv_cache`` : bool, optional
          Cache text and reference-image attention keys and values across
          denoising steps. When omitted, the pipeline default of ``True`` is
          used. Disabling it can change results in reduced precision, even
          with the same seed.

        ``prompt`` and ``negative_prompt`` follow the standard
        :class:`PromptBundle` contract. An upstream bundle attached through
        ``node.prompt()`` takes precedence over local prompt fields.

        ``seed`` : int or str, optional
            Random seed used for generation. Can be an integer or ``'random'``
            (default). The pipeline receives a CPU ``torch.Generator``.
    evict_after_run : bool, default=False
        If ``True``, evict the cached pipeline matching this node's model,
        dtype, device, offload, and tiling settings in ``post_run()``, followed
        by best-effort Python/CUDA cleanup.

    Inputs
    ------
    default : dict, optional
        Optional primary image payload, wired with ``src >> node``. Must
        contain ``'image'``, ``'images'``, or ``'path'``. Its image(s) appear
        first in the reference sequence, in payload order.
    prompt:default : dict, optional
        Optional upstream prompt bundle. Overrides corresponding prompt fields
        from ``spec``.
    image:<idx> : dict, optional
        Additional reference payload declared through ``image.add(idx=...)``,
        ``image(idx)``, or ``condition(idx)``. Uses the same payload keys as
        ``default``. These images follow the default images, sorted by ascending
        integer index. The total number of reference images must not exceed ten.

    Outputs
    -------
    dict
        Primary output dictionary with a single generated image and JSON
        sidecar:

        - ``ok`` : bool
        - ``node`` : str
          Operator identifier.
        - ``id`` : str
          Node identifier within the DAG.
        - ``image`` : str
          Path to the generated PNG, preserving the pipeline's alpha channel.
        - ``seed`` : int
          Resolved seed used for generation.
        - ``metadata`` : str
          Path to the JSON sidecar containing resolved parameters, reference
          image metadata, model/runtime settings, timing, and CUDA memory stats.

    Notes
    -----
    - Requires ``diffusers>=0.42.0`` and ``transformers>=5.17``.
    - The model weights have a non-commercial license, as described in the
      model card license section linked above. Check the license of any
      alternative checkpoint selected through ``model.id``.
    - Reference roles should be described explicitly in the prompt. A single
      reference is passed as a PIL image; multiple references form a flat list.
    - Request transparency explicitly, for example:
      ``'This is an RGBA image with transparency. A dragon sticker. The image
      has alpha channel and the background is transparent.'``
    - CUDA defaults to model CPU offload, following the model card's memory
      optimization example. ``model.device_map`` and ``model.checkpoint``
      overrides are not supported by this node.
    - CPU offload reduces resident weight memory but does not eliminate VAE
      activation peaks. Large output dimensions or reference images can still
      exhaust VRAM. Start at a resolution scale of 1024 with tiling disabled
      and increase dimensions according to available memory.
    - The pipeline is cached through ``get_qwen_image21_pipe(...)`` separately
      from older Qwen pipelines. Cache identity includes the model, dtype,
      device, CPU offload, and VAE tiling settings.
    """

    spec: SpecInput = field(default_factory=dict)
    evict_after_run: bool = False

    @property
    def uses_cuda(self) -> bool:
        spec = resolve_spec(self.spec)
        model = spec.get('model') or {}
        return is_cuda_device(model.get('device', 'cuda'))

    def condition(self, idx: int) -> AttachmentSink:
        """
        Declare an additional ordered reference image.

        This is an alias for ``self.image.add(idx=idx)``. Wire an upstream
        image-producing node into the returned sink using the ``>>`` operator.

        Parameters
        ----------
        idx : int
            Unique ordering index within this node's image registry. Lower
            indexes appear first after the optional default input images.

        Returns
        -------
        AttachmentSink
            Sink bound to this node with input identifier ``'image:<idx>'``.
            Reference roles are described through the prompt.
        """
        return self.image.add(idx)

    def run(
        self,
        output_dir: str | Path,
        input: Optional[Dict[str, Dict]] = None,
    ) -> Dict[str, Any]:
        # Spec
        input = input or {}
        spec = resolve_spec(self.spec)

        # Input images
        image_bundle = self.build_image_sequence_bundle(input, preserve_alpha=True)
        images = image_bundle.images
        image_metadata = image_bundle.metadata

        # Prompt
        pb = PromptBundle(spec=spec, input=input)
        prompt = pb.prompt
        negative = pb.negative_prompt
        if not prompt:
            raise ValueError('QwenImage21 requires a non-empty prompt.')

        # Model
        model = spec.get('model') or {}
        model_id = model.get('id', DEFAULT_QWEN_IMAGE21_MODEL_ID)
        dtype = resolve_dtype(model.get('dtype', 'bf16'))
        device = model.get('device', 'cuda')
        cpu_offload = bool(model.get('cpu_offload', True))
        vae_tiling = bool(model.get('vae_tiling', False))
        if 'device_map' in model:
            raise ValueError('QwenImage21 uses model.device and model.cpu_offload, not model.device_map.')
        if model.get('checkpoint') is not None:
            raise ValueError('QwenImage21 uses model.id; model.checkpoint is unsupported.')

        # Params
        params = resolve_qwen_image_edit_params(
            spec,
            default_steps=8 if model_id == QWEN_IMAGE21_TURBO_MODEL_ID else 40,
        )
        resolved_params = {'steps': params.steps}
        for key in ('height', 'width', 'true_cfg_scale'):
            value = getattr(params, key)
            if value is not None:
                resolved_params[key] = value

        # Qwen Image 2.1 options
        params_spec = spec.get('params') or {}
        if 'guidance_scale' in params_spec:
            raise ValueError('QwenImage21 uses params.true_cfg_scale, not guidance_scale.')
        if params_spec.get('output_resolution') is not None:
            resolved_params['output_resolution'] = int(params_spec['output_resolution'])
        if 'use_kv_cache' in params_spec:
            if not isinstance(params_spec['use_kv_cache'], bool):
                raise ValueError('QwenImage21 params.use_kv_cache must be a boolean.')
            resolved_params['use_kv_cache'] = params_spec['use_kv_cache']

        # Validation
        for key in ('steps', 'height', 'width', 'output_resolution'):
            if key in resolved_params and resolved_params[key] <= 0:
                raise ValueError(f'QwenImage21 params.{key} must be > 0.')
        if len(images) > 10:
            raise ValueError('QwenImage21 supports at most 10 input images.')

        # Seed / generator
        seed = resolve_qwen_seed(spec)
        gen = qwen_cpu_generator(seed)

        # Pipeline
        pipe = get_qwen_image21_pipe(
            model_id=model_id,
            dtype=dtype,
            device=device,
            cpu_offload=cpu_offload,
            vae_tiling=vae_tiling,
        )

        # CUDA stats / timing
        stats_device = device if is_cuda_device(device) else 'cpu'
        cuda_prerun(stats_device)
        t0 = time.perf_counter()

        # Pipeline arguments
        call_kwargs: Dict[str, Any] = {
            'prompt': prompt,
            'num_inference_steps': params.steps,
            'generator': gen,
            **{key: value for key, value in resolved_params.items() if key != 'steps'},
        }
        if negative:
            call_kwargs['negative_prompt'] = negative
        if images:
            call_kwargs['image'] = images[0] if len(images) == 1 else images

        # Inference
        result = pipe(**call_kwargs)

        # Timing
        cuda_sync(stats_device)
        dt_s = time.perf_counter() - t0

        # Save image / memory stats
        img = result.images[0]
        img_path = save_image(output_dir, node_id=self.id, seed=seed, img=img)
        mem = cuda_mem_stats(stats_device)

        # Output / metadata
        out = finalize_image_output(
            node_kind=str(self.op),
            node_id=self.id,
            img_path=img_path,
            seed=seed,
            params={
                **resolved_params,
                'num_input_images': len(images),
                'input_images': image_metadata,
            },
            dt_s=dt_s,
            cuda_mem=mem,
            model_info={
                'id': model_id,
                'device': device,
                'dtype': dtype_key(dtype),
                'cpu_offload': cpu_offload,
                'vae_tiling': vae_tiling,
                'pipeline': 'QwenImage21Pipeline',
            },
        )

        return out

    def post_run(self) -> None:
        """
        Synchronize CUDA and optionally evict the cached pipeline.

        Notes
        -----
        When ``evict_after_run`` is enabled, remove the cache entry matching
        the resolved model, dtype, device, CPU offload, and VAE tiling settings.
        Best-effort Python/CUDA cleanup runs even if eviction fails.
        """
        if self.uses_cuda:
            synchronize_torch_cuda()
        if not self.evict_after_run:
            return
        try:
            spec = resolve_spec(self.spec)
            model = spec.get('model') or {}
            model_id = model.get('id', DEFAULT_QWEN_IMAGE21_MODEL_ID)
            dtype = resolve_dtype(model.get('dtype', 'bf16'))
            device = model.get('device', 'cuda')
            cpu_offload = bool(model.get('cpu_offload', True))
            vae_tiling = bool(model.get('vae_tiling', False))

            obj = evict_qwen_image21_pipe(
                model_id=model_id,
                dtype=dtype,
                device=device,
                cpu_offload=cpu_offload,
                vae_tiling=vae_tiling,
            )
            if obj is None:
                raise RuntimeError(
                    'QwenImage21 cache model not found for eviction: '
                    f'model_id={model_id!r}, device={device!r}, '
                    f'cpu_offload={cpu_offload!r}, dtype={dtype!r}'
                )
            del obj
        finally:
            cleanup_torch_cuda()
